select c.customer_name,count(c.customer_id) as Frequency
from sales s
join customers c
on s.customer_id=c.customer_id
group by c.customer_name
order by Frequency desc;

select sale_date,total_amount,sum(total_amount) over (order by sale_id,sale_date) as RunningRevenue
from sales 
order by sale_id,sale_date;

WITH customer_total AS (
    SELECT
        c.customer_id,
        c.customer_name,
        SUM(s.total_amount) AS revenue
    FROM sales s
    JOIN customers c
        ON c.customer_id = s.customer_id
    GROUP BY
        c.customer_id,
        c.customer_name
)
SELECT
    customer_id,
    customer_name,
    revenue,
    RANK() OVER (ORDER BY revenue DESC) AS customer_rank
FROM customer_total
ORDER BY customer_rank;

CREATE OR REPLACE VIEW CUSTOMER_REVENUE AS
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM SALES S
JOIN CUSTOMERS C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME;

SELECT *
FROM CUSTOMER_REVENUE
ORDER BY TOTAL_REVENUE DESC;