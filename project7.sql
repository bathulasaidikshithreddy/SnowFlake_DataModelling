from dim_hospitals h 
join fact_billing f
on h.hospital_key=f.hospital_key

select to_char(d.full_date,'YYYY-MM') as month,sum(f.net_amount) as total_revenue
from fact_billing f
join dim_date d
on f.date_key=d.date_key
