SELECT
    h.hospital_name,
    SUM(a.admission_count) AS total_admissions
FROM FACT_ADMISSION AS a
JOIN DIM_HOSPITALS AS h
    ON a.hospital_key = h.hospital_key
GROUP BY
    h.hospital_name
ORDER BY
    total_admissions DESC;


SELECT
    h.hospital_name,
    SUM(f.net_amount) AS total_revenue
FROM FACT_BILLING AS f
JOIN DIM_HOSPITALS AS h
    ON f.hospital_key = h.hospital_key
GROUP BY
    h.hospital_name
ORDER BY
    total_revenue DESC;

