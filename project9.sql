CREATE WAREHOUSE IF NOT EXISTS CUSTOMER_SCD_WH
WAREHOUSE_SIZE = 'XSMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE;

USE WAREHOUSE CUSTOMER_SCD_WH;

CREATE DATABASE IF NOT EXISTS CUSTOMER_SCD_DB;

USE DATABASE CUSTOMER_SCD_DB;

CREATE SCHEMA IF NOT EXISTS CUSTOMER_SCD_SCHEMA;

USE SCHEMA CUSTOMER_SCD_SCHEMA;

create or replace table customer_initial (
customer_id number,
customer_name varchar(40),
city varchar(30),
state varchar(30),
membership varchar(30),
segment varchar(30)
);

CREATE OR REPLACE TABLE CUSTOMER_UPDATES (
    CUSTOMER_ID NUMBER,
    CUSTOMER_NAME VARCHAR(100),
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    MEMBERSHIP VARCHAR(30),
    SEGMENT VARCHAR(30),
    EFFECTIVE_DATE DATE
);

CREATE OR REPLACE TABLE DIM_CUSTOMER_TYPE1 (
    CUSTOMER_KEY NUMBER AUTOINCREMENT,
    CUSTOMER_ID NUMBER,
    CUSTOMER_NAME VARCHAR(100),
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    MEMBERSHIP VARCHAR(30),
    SEGMENT VARCHAR(30)
);

CREATE OR REPLACE FILE FORMAT CUSTOMER_CSV_FORMAT
TYPE = 'CSV'
FIELD_DELIMITER = ','
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
TRIM_SPACE = TRUE
EMPTY_FIELD_AS_NULL = TRUE;

CREATE OR REPLACE STAGE CUSTOMER_SCD_STAGE
FILE_FORMAT = CUSTOMER_CSV_FORMAT;

