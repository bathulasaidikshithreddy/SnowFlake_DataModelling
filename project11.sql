(
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    PREVIOUS_CITY,
    STATE,
    CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP,
    HISTORICAL_MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE,
    EXPIRY_DATE,
    IS_CURRENT
)
SELECT
    CUSTOMER_ID,

    CUSTOMER_NAME,

    NEW_CITY,

    OLD_CITY AS PREVIOUS_CITY,

    NEW_STATE,

    NEW_MEMBERSHIP AS CURRENT_MEMBERSHIP,

    OLD_MEMBERSHIP AS PREVIOUS_MEMBERSHIP,

    NEW_MEMBERSHIP AS HISTORICAL_MEMBERSHIP,

    NEW_SEGMENT AS SEGMENT,

    EFFECTIVE_DATE,

    '9999-12-31'::DATE,

    TRUE

FROM CUSTOMER_UPDATE_CONTEXT;

UPDATE CUSTOMER_HYBRID_DIM D
SET
    CUSTOMER_NAME = C.CUSTOMER_NAME,

    CITY = C.NEW_CITY,

    STATE = C.NEW_STATE,

    CURRENT_MEMBERSHIP = C.NEW_MEMBERSHIP,

    PREVIOUS_MEMBERSHIP = C.OLD_MEMBERSHIP

FROM CUSTOMER_UPDATE_CONTEXT C

WHERE D.CUSTOMER_ID = C.CUSTOMER_ID;

SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    PREVIOUS_CITY,
    STATE,
    CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP,
    HISTORICAL_MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE,
    EXPIRY_DATE,
    IS_CURRENT
FROM CUSTOMER_HYBRID_DIM
ORDER BY CUSTOMER_ID, EFFECTIVE_DATE;

SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    PREVIOUS_CITY,
    STATE,
    CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP,
    SEGMENT
FROM CUSTOMER_HYBRID_DIM
WHERE IS_CURRENT = TRUE
ORDER BY CUSTOMER_ID;

SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    HISTORICAL_MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE,
    EXPIRY_DATE
FROM CUSTOMER_HYBRID_DIM
