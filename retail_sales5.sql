    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    d.DATE
ORDER BY
    c.CUSTOMER_ID,
    d.DATE;

SELECT
    p.PRODUCT_ID,
    p.PRODUCT_NAME,
    p.CATEGORY,
    p.BRAND,
    SUM(f.QUANTITY) AS TOTAL_UNITS_SOLD,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE,
    AVG(f.TOTAL_AMOUNT) AS AVG_SALE_AMOUNT
FROM FACT_SALES f
JOIN DIM_PRODUCT p
    ON f.PRODUCT_ID = p.PRODUCT_ID
GROUP BY
    p.PRODUCT_ID,
    p.PRODUCT_NAME,
    p.CATEGORY,
    p.BRAND
ORDER BY
    TOTAL_REVENUE DESC;

SELECT
    b.BRANCH_ID,
    b.BRANCH_NAME,
    b.CITY,
    b.STATE,
    b.REGION,
    SUM(f.QUANTITY) AS TOTAL_UNITS_SOLD,
    COUNT(DISTINCT f.SALE_ID) AS TOTAL_TRANSACTIONS,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE,
    AVG(f.TOTAL_AMOUNT) AS AVG_TRANSACTION_VALUE
FROM FACT_SALES f
JOIN DIM_BRANCH b
    ON f.BRANCH_ID = b.BRANCH_ID
GROUP BY
    b.BRANCH_ID,
    b.BRANCH_NAME,
    b.CITY,
    b.STATE,
    b.REGION
ORDER BY
    TOTAL_REVENUE DESC;